"use client";

import React from "react";
import { BarChart, Bar, Cell, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer } from "recharts";
import { PackageMinus, PiggyBank, Percent, Landmark, TrendingUp, Gauge } from "lucide-react";
import { formatMoney } from "../../data/mockData";
import { KpiCard, Panel, Hero, NoData, PALETTE } from "./PharmUi";

const axisMoney = (v) => (v >= 1000 ? `₹${Math.round(v / 1000)}k` : `₹${v}`);
const tipStyle = { borderRadius: 12, fontSize: 12, border: "1px solid #e5e7eb" };

export default function ProfitTab({ data }) {
  const t = data.totals;
  const cogsShare = t.netExTax > 0 ? (t.cogs / t.netExTax) * 100 : 0;
  const gstShare = t.net > 0 ? (t.gst / t.net) * 100 : 0;
  const rows = [...data.categories]
    .sort((a, b) => b.profit - a.profit)
    .map((c) => ({ short: c.short, name: c.name, value: c.profit }));

  return (
    <div className="space-y-6">
      <Hero
        bg="bg-emerald-700" badge="Profitability" icon={Gauge} title="Profit & Margin Pulse"
        description="What is left from each rupee of sales after tax and medicine purchase cost."
        rings={[
          { value: t.margin, label: "Gross Margin", sub: "on sales excl. tax", color: "#fde047" },
          { value: cogsShare, label: "Cost of Goods", sub: "share of sales excl. tax", color: "#fda4af" },
          { value: gstShare, label: "GST Share", sub: "of GST-inclusive sales", color: "#7dd3fc" },
        ]}
      />

      <div className="grid grid-cols-2 xl:grid-cols-4 gap-3.5">
        <KpiCard tone="violet" label="Cost of Goods Sold" value={formatMoney(t.cogs)} sub="Purchase cost of medicines sold" icon={PackageMinus} />
        <KpiCard tone="emerald" label="Gross Profit" value={formatMoney(t.profit)} sub="Net sales excl. tax − COGS" icon={PiggyBank} />
        <KpiCard tone="amber" label="Gross Profit Margin" value={`${t.margin.toFixed(1)}%`} sub="Profit on sales" icon={Percent} />
        <KpiCard tone="sky" label="GST Collected" value={formatMoney(t.gst)} sub="Output tax on sales" icon={Landmark} />
      </div>

      <Panel accent="border-t-emerald-500" icon={TrendingUp} title="Profit by Medicine Category" subtitle="Gross profit generated by each drug class">
        <div className="h-72">
          {rows.length === 0 ? (
            <NoData />
          ) : (
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={rows} margin={{ top: 8, right: 8, left: -8, bottom: 0 }}>
                <CartesianGrid stroke="#f1f5f9" strokeDasharray="3 3" vertical={false} />
                <XAxis dataKey="short" tick={{ fontSize: 11, fill: "#64748b" }} tickLine={false} axisLine={false} />
                <YAxis tick={{ fontSize: 10, fill: "#94a3b8" }} tickLine={false} axisLine={false} tickFormatter={axisMoney} />
                <Tooltip cursor={{ fill: "#f8fafc" }} labelFormatter={(_, p) => p?.[0]?.payload?.name || ""} formatter={(v) => [formatMoney(v), "Gross profit"]} contentStyle={tipStyle} />
                <Bar dataKey="value" radius={[6, 6, 0, 0]} maxBarSize={56}>
                  {rows.map((r, i) => <Cell key={r.short} fill={PALETTE[(i + 2) % PALETTE.length]} />)}
                </Bar>
              </BarChart>
            </ResponsiveContainer>
          )}
        </div>
      </Panel>
    </div>
  );
}
